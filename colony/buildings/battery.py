"""
battery.py

Part 1/5

Canonical Battery Bank.

Stores electrical energy generated by
Solar Arrays and Reactors.

Consumes

- Power (charging)

Produces

- Power (discharging)
"""

from __future__ import annotations

from dataclasses import dataclass
from dataclasses import field

from colony.buildings.base_building import BaseBuilding

from colony.resources.power import Power

# ============================================================
# Battery Bank
# ============================================================


@dataclass
class Battery(BaseBuilding):

    building_id: int = 0

    name: str = "Battery Bank"

    position: tuple[int, int] = (0, 0)

    level: int = 1

    description: str = "High-capacity electrical energy storage system."

    storage_capacity: float = 5000.0

    charge_rate: float = 150.0

    discharge_rate: float = 150.0

    charge_efficiency: float = 0.95

    discharge_efficiency: float = 0.95

    self_discharge_rate: float = 0.001

    stored_energy: float = 2500.0

    reserve_percentage: float = 0.15

    power: Power = field(
        default_factory=Power,
    )

    total_energy_charged: float = 0.0

    total_energy_discharged: float = 0.0

    # ========================================================
    # Runtime
    # ========================================================

    def step(
        self,
    ) -> None:

        super().step()

        if not self.operational:

            return

        self.self_discharge()

        self.update_integrity()

    # ========================================================
    # Integrity
    # ========================================================

    def update_integrity(
        self,
    ) -> None:

        self.efficiency = self.health_percentage / 100.0

    # ========================================================
    # Charging
    # ========================================================

    def charge(
        self,
        amount: float,
    ) -> float:

        if amount <= 0.0 or not self.operational:

            return 0.0

        accepted = min(
            amount,
            self.charge_rate,
            self.available_capacity,
        )

        accepted *= self.charge_efficiency

        self.stored_energy += accepted

        self.total_energy_charged += accepted

        return accepted

    # ========================================================
    # Discharging
    # ========================================================

    def discharge(
        self,
        amount: float,
    ) -> float:

        if amount <= 0.0 or not self.operational:

            return 0.0

        reserve = self.storage_capacity * self.reserve_percentage

        available = max(
            0.0,
            self.stored_energy - reserve,
        )

        delivered = min(
            amount,
            self.discharge_rate,
            available,
        )

        delivered *= self.discharge_efficiency

        self.stored_energy -= delivered

        self.total_energy_discharged += delivered

        self.power.generate(
            delivered,
        )

        return delivered

    # ========================================================
    # Passive Losses
    # ========================================================

    def self_discharge(
        self,
    ) -> None:

        if self.stored_energy <= 0.0:

            return

        self.stored_energy = max(
            0.0,
            self.stored_energy - (self.stored_energy * self.self_discharge_rate),
        )

        # ========================================================

    # Status
    # ========================================================

    @property
    def charge_percentage(
        self,
    ) -> float:

        if self.storage_capacity <= 0:

            return 0.0

        return (self.stored_energy / self.storage_capacity) * 100.0

    @property
    def available_capacity(
        self,
    ) -> float:

        return max(
            0.0,
            self.storage_capacity - self.stored_energy,
        )

    @property
    def reserve_energy(
        self,
    ) -> float:

        return self.storage_capacity * self.reserve_percentage

    @property
    def usable_energy(
        self,
    ) -> float:

        return max(
            0.0,
            self.stored_energy - self.reserve_energy,
        )

    @property
    def is_full(
        self,
    ) -> bool:

        return self.stored_energy >= self.storage_capacity

    @property
    def is_empty(
        self,
    ) -> bool:

        return self.usable_energy <= 0.0

    # ========================================================
    # Statistics
    # ========================================================

    def statistics(
        self,
    ) -> dict:

        stats = super().statistics()

        stats.update(
            {
                "stored_energy": round(
                    self.stored_energy,
                    2,
                ),
                "storage_capacity": round(
                    self.storage_capacity,
                    2,
                ),
                "charge_percentage": round(
                    self.charge_percentage,
                    2,
                ),
                "usable_energy": round(
                    self.usable_energy,
                    2,
                ),
                "available_capacity": round(
                    self.available_capacity,
                    2,
                ),
                "reserve_energy": round(
                    self.reserve_energy,
                    2,
                ),
                "charge_rate": round(
                    self.charge_rate,
                    2,
                ),
                "discharge_rate": round(
                    self.discharge_rate,
                    2,
                ),
                "charge_efficiency": round(
                    self.charge_efficiency,
                    3,
                ),
                "discharge_efficiency": round(
                    self.discharge_efficiency,
                    3,
                ),
                "self_discharge_rate": round(
                    self.self_discharge_rate,
                    4,
                ),
                "total_energy_charged": round(
                    self.total_energy_charged,
                    2,
                ),
                "total_energy_discharged": round(
                    self.total_energy_discharged,
                    2,
                ),
                "power": self.power.statistics(),
            }
        )

        return stats

    # ========================================================
    # Maintenance
    # ========================================================

    def replace_cells(
        self,
    ) -> None:

        self.charge_efficiency = 0.95

        self.discharge_efficiency = 0.95

        self.self_discharge_rate = 0.001

    def calibrate(
        self,
        bonus: float = 0.01,
    ) -> None:

        self.charge_efficiency = min(
            1.0,
            self.charge_efficiency + bonus,
        )

        self.discharge_efficiency = min(
            1.0,
            self.discharge_efficiency + bonus,
        )

    def expand_capacity(
        self,
        additional_capacity: float,
    ) -> None:

        if additional_capacity <= 0:

            return

        self.storage_capacity += additional_capacity

    # ========================================================
    # Utility
    # ========================================================

    def __repr__(
        self,
    ) -> str:

        return (
            "Battery("
            f"charge={self.charge_percentage:.1f}%, "
            f"stored={self.stored_energy:.2f} kWh, "
            f"capacity={self.storage_capacity:.2f} kWh, "
            f"usable={self.usable_energy:.2f} kWh"
            ")"
        )


# ============================================================
# Canonical Alias
# ============================================================

BatteryBank = Battery
